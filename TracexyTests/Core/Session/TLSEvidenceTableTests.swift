    // MARK: SessionAccumulator wiring — direct + reassembled through the real fold

    @Test
    func splitClientHelloRetainsDirectFragmentAndExcludesRecoveredRecord() throws {
        var accumulator = SessionAccumulator()
        // A TLS ClientHello split across two TCP segments of one five-tuple: the first
        // segment carries a direct (fragment) record; the completing segment starts
        // mid-record, so its record is recovered only by the connection prefix probe.
        let hello = PacketBuilder.tlsClientHello(sni: "secure.example")
        let cut = hello.count / 2
        add(&accumulator, tcpTLSFrame(
            payload: Array(hello[..<cut]), src: client, dst: server, srcPort: 52_344, sequence: 1_000
        ))
        add(&accumulator, tcpTLSFrame(
            payload: Array(hello[cut...]), src: client, dst: server, srcPort: 52_344,
            sequence: 1_000 + UInt32(cut)
        ))

        let fold = accumulator.foldSnapshot()
        let tls = fold.tlsEvidence
        let summary = try #require(tls.summaries.first)
        // Exactly one direct observation was retained: the first segment's fragment
        // record (an honest incomplete body), never the recovered complete record.
        #expect(tls.retainedObservationCount == 1)
        #expect(summary.observations.count == 1)
        #expect(summary.observations[0].fact.bodyComplete == false)
        // The completing frame's recovered record is excluded-counted, not retained.
        #expect(tls.excludedReassembledRecordCount >= 1)
        // The reassembly path genuinely classified TLS (proving the exclusion covers a
        // recovered fact, not merely an absent one).
        #expect(fold.connections.summaries.contains { summary in
            summary.events.contains { $0.applicationKind == .tls }
        })
    }

    @Test
    func completeSingleFrameHelloIsNeverDoubleCountedThroughTheFold() {
        var accumulator = SessionAccumulator()
        add(&accumulator, PacketBuilder.tlsClientHelloFrame(
            sni: "solo.example", src: client, dst: server, srcPort: 40_900
        ))
        let fold = accumulator.foldSnapshot()
        let tls = fold.tlsEvidence
        #expect(tls.summaries.count == 1)
        #expect(tls.retainedObservationCount == 1)
        // The reassembled handoff exists and carries the same record, but the direct
        // frame suppresses excluding it — no double count.
        #expect(fold.connections.summaries.contains { summary in
            summary.events.contains { $0.applicationKind == .tls }
        })
        #expect(tls.excludedReassembledRecordCount == 0)
    }

    @Test
    func acceptedOrdinalsAdvanceAcrossInterveningNonTLSFrames() throws {
        var accumulator = SessionAccumulator()
        // ordinal 1: ARP (ignored), 2: UDP DNS (ignored by TLS), 3: TLS ClientHello.
        add(&accumulator, PacketBuilder.arpRequestFrame(senderIP: client, targetIP: server))
        add(&accumulator, PacketBuilder.dnsQueryFrame(name: "x.example", src: client, dst: server))
        add(
            &accumulator,
            PacketBuilder.tlsClientHelloFrame(sni: "z.example", src: client, dst: server, srcPort: 41_000)
        )

        let tls = accumulator.foldSnapshot().tlsEvidence
        let summary = try #require(tls.summaries.first)
        #expect(tls.summaries.count == 1)
        #expect(summary.observations[0].provenance.ordinal == FrameOrdinal(3))
    }

    @Test
    func resetClearsTLSEvidenceAndPreservesConfiguration() throws {
        var accumulator = SessionAccumulator(tlsConfiguration: .init(maxObservationsPerSummary: 2))
        for _ in 0 ..< 5 {
            add(&accumulator, PacketBuilder.tlsClientHelloFrame(
                sni: "keep.example", src: client, dst: server, srcPort: 41_100
            ))
        }
        // Injected tiny bound bit before reset (single flow, five ClientHellos → cap 2).
        #expect(accumulator.foldSnapshot().tlsEvidence.capacityReached)
        accumulator.reset()
        #expect(accumulator.foldSnapshot().tlsEvidence == .empty)
        // Configuration is preserved across reset: the same tiny cap still bites.
        for _ in 0 ..< 5 {
            add(&accumulator, PacketBuilder.tlsClientHelloFrame(
                sni: "keep.example", src: client, dst: server, srcPort: 41_100
            ))
        }
        let after = accumulator.foldSnapshot().tlsEvidence
        #expect(try #require(after.summaries.first).observations.count == 2)
    }

    // MARK: Private

    private let client = "198.51.100.10"
    private let server = "203.0.113.5"
    private let otherServer = "203.0.113.6"

    private func instant(_ ordinal: UInt64) -> Date {
        Date(timeIntervalSince1970: 1_700_000_000 + Double(ordinal))
    }

    private func provenance(_ ordinal: UInt64) -> SessionFrameProvenance {
        SessionFrameProvenance(
            ordinal: FrameOrdinal(ordinal),
            timestamp: instant(ordinal),
            capturedLength: 0,
            originalLength: 0,
            linkType: LinkType.ethernet
        )
    }

    private func decode(_ bytes: [UInt8], linkType: UInt32 = LinkType.ethernet) -> DecodedPacket {
        var packet = PacketDecoder.decode(
            PacketBuffer(bytes), linkType: linkType, timestamp: instant(0), originalLength: bytes.count
        )
        packet.rawBytes = bytes
        return packet
    }

    /// An Ethernet+IPv4+TCP frame carrying the given TLS payload (coalesced records).
    private func tcpTLSFrame(
        payload: [UInt8],
        src: String,
        dst: String,
        srcPort: UInt16,
        dstPort: UInt16 = 443,
        sequence: UInt32 = 1
    )
        -> [UInt8]
    {
        PacketBuilder.ethernetIPv4(
            proto: 6, src: src, dst: dst,
            payload: PacketBuilder.tcp(
                srcPort: srcPort, dstPort: dstPort, flags: 0x18, payload: payload, sequence: sequence
            )
        )
    }

    /// A synthetic reassembled application handoff carrying `records` neutral TLS record
    /// facts and an optional recovered truncation indicator — the shape the connection
    /// prefix probe produces, minted directly so a table test can pin exclusion.
    private func reassembled(records: Int, truncated: Bool) -> PacketDecoder.ReassembledTCPApplication {
        let fact = TLSRecordFact(
            contentType: 23, legacyRecordVersion: 0x0303, declaredBodyLength: 4,
            capturedBodyLength: 4, handshake: nil
        )
        return PacketDecoder.ReassembledTCPApplication(
            appProtocol: .tls, layers: [], sni: nil, dnsQuery: nil, dnsAnswers: [],
            dnsAnswersOmittedCount: 0, dnsFacts: nil,
            tlsRecords: Array(repeating: fact, count: records), tlsRecordsTruncated: truncated, isComplete: true
        )
    }

    /// Fold one frame's bytes through the common accumulator path with a nil-locator
    /// batch-style context, so ordinals are assigned exactly as batch/live do.
    private func add(_ accumulator: inout SessionAccumulator, _ bytes: [UInt8]) {
        let frame = CapturedFrame(bytes: bytes, timestamp: instant(0), originalLength: bytes.count)
        let packet = SessionBuilder.decodePacket(frame, linkType: LinkType.ethernet)
        accumulator.add(packet, context: SessionBuilder.frameContext(for: frame, linkType: LinkType.ethernet))
    }
}
