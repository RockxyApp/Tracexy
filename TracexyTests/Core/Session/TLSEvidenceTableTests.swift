// MARK: - Byte helpers

private func be16(_ value: UInt16) -> [UInt8] {
    [UInt8(value >> 8), UInt8(value & 0xFF)]
}

/// Wraps a raw TLS record body into record bytes (header + body).
private func tlsRecordBytes(contentType: UInt8, version: UInt16 = 0x0303, body: [UInt8]) -> [UInt8] {
    [contentType] + be16(version) + be16(UInt16(body.count)) + body
}

// MARK: - TLSEvidenceTableTests

/// Direct, adversarial coverage of the bounded TLS record evidence fold plus the
/// `SessionAccumulator` wiring that feeds it. Every fixture is generated by
/// `PacketBuilder` from reserved documentation addresses; no capture is read and no
/// SNI/host/certificate string is ever asserted to appear in the evidence — the fold
/// retains only typed `TLSRecordFact` wire facts with exact direct-frame provenance.
struct TLSEvidenceTableTests {
    // MARK: Internal

    // MARK: Direct record retention: order, index, direction, provenance

    @Test
    func directRecordsRetainInOrderWithIndexAndCanonicalDirection() throws {
        var table = TLSEvidenceTable()
        // Two coalesced records in one client→server frame, then one server→client
        // record of the same canonical tuple.
        let clientFrame = tcpTLSFrame(
            payload: tlsRecordBytes(contentType: 22, body: [0x01, 0x02])
                + tlsRecordBytes(contentType: 23, body: [0xAA]),
            src: client, dst: server, srcPort: 44_000
        )
        let serverFrame = tcpTLSFrame(
            payload: tlsRecordBytes(contentType: 22, body: [0x02, 0x00, 0x00, 0x00]),
            src: server, dst: client, srcPort: 443, dstPort: 44_000
        )
        let clientPacket = decode(clientFrame)
        let serverPacket = decode(serverFrame)
        table.offer(clientPacket, application: nil, provenance: provenance(1))
        table.offer(serverPacket, application: nil, provenance: provenance(2))

        let snapshot = table.snapshot()
        #expect(snapshot.summaries.count == 1)
        let summary = try #require(snapshot.summaries.first)
        #expect(summary.observations.count == 3)
        // Within-frame record index is zero-based and ordered; frame order is preserved.
        #expect(summary.observations.map(\.recordIndex) == [0, 1, 0])
        #expect(summary.observations.map(\.provenance.ordinal.rawValue) == [1, 1, 2])
        // The two directions are opposite (canonical aToB vs bToA), and same-direction
        // records within one frame share a direction.
        #expect(summary.observations[0].direction == summary.observations[1].direction)
        #expect(summary.observations[0].direction != summary.observations[2].direction)
        #expect(Set(summary.observations.map(\.direction)).count == 2)
        // Privacy-by-type: the retained fact is exactly the decoder's typed record fact.
        #expect(summary.observations[0].fact == clientPacket.tlsRecords[0])
        #expect(summary.observations[1].fact == clientPacket.tlsRecords[1])
        #expect(try summary.sessionID == SessionBuilder.sessionID(for: #require(clientPacket.fiveTuple)))
        #expect(snapshot.retainedObservationCount == 3)
        #expect(snapshot.excludedReassembledRecordCount == 0)
        #expect(!snapshot.capacityReached)
    }

    @Test
    func nonTLSAndTuplelessFramesAreIgnored() {
        var table = TLSEvidenceTable()
        // ARP carries no tuple; a bare TCP SYN (no payload) carries no TLS record.
        table.offer(
            decode(PacketBuilder.arpRequestFrame(senderIP: client, targetIP: server)),
            application: nil,
            provenance: provenance(1)
        )
        table.offer(
            decode(PacketBuilder.tcpSynFrame(src: client, dst: server, srcPort: 40_000, dstPort: 443)),
            application: nil,
            provenance: provenance(2)
        )
        #expect(table.snapshot() == .empty)
    }

    // MARK: Decoder truncation (direct 32-record cap)

    @Test
    func directDecoderTruncationIsCountedPerFrameWithoutInventingRecords() throws {
        var table = TLSEvidenceTable()
        let unit = tlsRecordBytes(contentType: 23, body: [0xAB])
        let packet = decode(tcpTLSFrame(
            payload: Array(repeating: unit, count: 33).flatMap { $0 }, src: client, dst: server, srcPort: 44_100
        ))
        // The decoder capped the direct walk at 32 and flagged truncation.
        #expect(packet.tlsRecords.count == 32)
        #expect(packet.tlsRecordsTruncated)
        table.offer(packet, application: nil, provenance: provenance(1))

        let snapshot = table.snapshot()
        // Exactly the 32 captured records are retained; the unknown remainder is a
        // per-frame lower-bound coverage count, never a fabricated record total.
        #expect(snapshot.retainedObservationCount == 32)
        #expect(snapshot.decoderTruncatedFrameCount == 1)
        #expect(try #require(snapshot.summaries.first).decoderTruncatedFrameCount == 1)
        #expect(snapshot.excludedReassembledRecordCount == 0)
    }

    // MARK: Reassembled exclusion and recovered truncation (table level)

    @Test
    func reassembledRecordsAreExcludedCountedNeverRetained() throws {
        var table = TLSEvidenceTable()
        // A carrier frame with a tuple but no direct TLS record (a bare payload-less
        // segment), plus a reassembled handoff carrying two recovered records and a
        // recovered truncation indicator.
        let carrier = decode(PacketBuilder.tcpSynFrame(src: client, dst: server, srcPort: 44_200, dstPort: 443))
        #expect(carrier.tlsRecords.isEmpty)
        table.offer(carrier, application: reassembled(records: 2, truncated: true), provenance: provenance(1))

        let snapshot = table.snapshot()
        // No record was retained or cited; the recovered records/truncation are counted
        // as truthful coverage against the flow's summary and globally.
        #expect(snapshot.retainedObservationCount == 0)
        #expect(snapshot.excludedReassembledRecordCount == 2)
        #expect(snapshot.recoveredTruncationIndicatorCount == 1)
        let summary = try #require(snapshot.summaries.first)
        #expect(summary.observations.isEmpty)
        #expect(summary.excludedReassembledRecordCount == 2)
        #expect(summary.recoveredTruncationIndicatorCount == 1)
    }

    @Test
    func directFrameSuppressesReassembledExclusionToAvoidDoubleCount() {
        var table = TLSEvidenceTable()
        // A complete single-frame record has direct facts; the same frame's reassembled
        // handoff also carries records, but must not be excluded-counted.
        let packet = decode(tcpTLSFrame(
            payload: tlsRecordBytes(contentType: 22, body: [0x01, 0x02, 0x03]), src: client, dst: server,
            srcPort: 44_300
        ))
        #expect(!packet.tlsRecords.isEmpty)
        table.offer(packet, application: reassembled(records: 5, truncated: true), provenance: provenance(1))

        let snapshot = table.snapshot()
        #expect(snapshot.retainedObservationCount == packet.tlsRecords.count)
        #expect(snapshot.excludedReassembledRecordCount == 0)
        #expect(snapshot.recoveredTruncationIndicatorCount == 0)
    }

    // MARK: Sticky loss and snap truncation

    @Test
    func lossKnowledgeMergesStickilyAndSnapTruncationIsObserved() throws {
        var table = TLSEvidenceTable()
        let record = tlsRecordBytes(contentType: 23, body: [0x00])
        let first = decode(tcpTLSFrame(payload: record, src: client, dst: server, srcPort: 44_400))
        table.offer(first, application: nil, provenance: SessionFrameProvenance(
            ordinal: FrameOrdinal(1), timestamp: instant(1),
            capturedLength: first.rawBytes.count, originalLength: first.rawBytes.count + 100,
            linkType: LinkType.ethernet
        ), loss: .lossReported)
        // A later weaker report never downgrades the sticky knowledge.
        table.offer(
            decode(tcpTLSFrame(payload: record, src: client, dst: server, srcPort: 44_400)),
            application: nil, provenance: provenance(2), loss: .unknown
        )
        let summary = try #require(table.snapshot().summaries.first)
        #expect(summary.lossKnowledge == .lossReported)
        #expect(summary.snapLengthTruncationObserved)
    }

    @Test
    func lossAndSnapMetadataSurviveOmittedAndExcludedFacts() throws {
        var table = TLSEvidenceTable(configuration: .init(maxObservationsPerSummary: 1))
        let record = tlsRecordBytes(contentType: 23, body: [0x00])
        let retained = decode(tcpTLSFrame(payload: record, src: client, dst: server, srcPort: 44_401))
        table.offer(retained, application: nil, provenance: provenance(1))

        let omitted = decode(tcpTLSFrame(payload: record, src: client, dst: server, srcPort: 44_401))
        table.offer(omitted, application: nil, provenance: SessionFrameProvenance(
            ordinal: FrameOrdinal(2), timestamp: instant(2),
            capturedLength: omitted.rawBytes.count, originalLength: omitted.rawBytes.count + 1,
            linkType: LinkType.ethernet
        ), loss: .lossReported)

        let excludedCarrier = decode(PacketBuilder.tcpSynFrame(
            src: client, dst: otherServer, srcPort: 44_402, dstPort: 443
        ))
        table.offer(
            excludedCarrier,
            application: reassembled(records: 1, truncated: false),
            provenance:
            SessionFrameProvenance(
                ordinal: FrameOrdinal(3), timestamp: instant(3),
                capturedLength: excludedCarrier.rawBytes.count,
                originalLength: excludedCarrier.rawBytes.count + 1,
                linkType: LinkType.ethernet
            ),
            loss: .lossReported
        )

        let snapshot = table.snapshot()
        let omittedSummary = try #require(snapshot.summaries.first {
            $0.tuple.a.port == 44_401 || $0.tuple.b.port == 44_401
        })
        #expect(omittedSummary.omittedObservationCount == 1)
        #expect(omittedSummary.lossKnowledge == .lossReported)
        #expect(omittedSummary.snapLengthTruncationObserved)

        let excludedSummary = try #require(snapshot.summaries.first {
            $0.tuple.a.port == 44_402 || $0.tuple.b.port == 44_402
        })
        #expect(excludedSummary.observations.isEmpty)
        #expect(excludedSummary.excludedReassembledRecordCount == 1)
        #expect(excludedSummary.lossKnowledge == .lossReported)
        #expect(excludedSummary.snapLengthTruncationObserved)
    }

    // MARK: Bounds — exact occurrence omissions

    @Test
    func perSummaryCapRetainsBoundAndCountsExactOmissions() throws {
        var table = TLSEvidenceTable(configuration: .init(maxObservationsPerSummary: 2))
        for ordinal in 1 ... 5 {
            table.offer(
                decode(tcpTLSFrame(
                    payload: tlsRecordBytes(contentType: 23, body: [0x01]),
                    src: client,
                    dst: server,
                    srcPort: 44_500
                )),
                application: nil, provenance: provenance(UInt64(ordinal))
            )
        }
        let snapshot = table.snapshot()
        let summary = try #require(snapshot.summaries.first)
        #expect(summary.observations.count == 2)
        #expect(summary.omittedObservationCount == 3)
        #expect(snapshot.omittedObservationCount == 3)
        #expect(snapshot.retainedObservationCount == 2)
        #expect(snapshot.capacityReached)
    }

