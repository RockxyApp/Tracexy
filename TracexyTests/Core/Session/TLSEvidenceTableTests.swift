    @Test
    func summaryCapDropsNewFlowAndCountsEveryOccurrenceGlobally() {
        var table = TLSEvidenceTable(configuration: .init(maxSummaries: 1))
        table.offer(
            decode(tcpTLSFrame(
                payload: tlsRecordBytes(contentType: 22, body: [0x00]),
                src: client,
                dst: server,
                srcPort: 44_700
            )),
            application: nil, provenance: provenance(1)
        )
        // A second, distinct flow after the summary cap: not retained; each direct
        // record occurrence is one global omission, and recovered coverage still counts.
        let carrier = decode(PacketBuilder.tcpSynFrame(src: client, dst: otherServer, srcPort: 44_701, dstPort: 443))
        table.offer(carrier, application: reassembled(records: 3, truncated: true), provenance: provenance(2))
        table.offer(
            decode(tcpTLSFrame(
                payload: tlsRecordBytes(contentType: 22, body: [0x00])
                    + tlsRecordBytes(contentType: 23, body: [0x01]),
                src: client,
                dst: otherServer,
                srcPort: 44_701
            )),
            application: nil, provenance: provenance(3)
        )
        let snapshot = table.snapshot()
        #expect(snapshot.summaries.count == 1)
        #expect(snapshot.retainedObservationCount == 1)
        #expect(snapshot.omittedObservationCount == 2) // two direct records on the dropped flow
        #expect(snapshot.excludedReassembledRecordCount == 3)
        #expect(snapshot.recoveredTruncationIndicatorCount == 1)
        #expect(snapshot.capacityReached)
    }

